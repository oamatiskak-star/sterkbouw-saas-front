// Prijspeil waarop de curated kostprijs-kengetallen zijn geijkt (laatst beschikbare maand).
export const BASIS_PRIJSPEIL = '2026-04';

function indexVoorReeks(reeks, ym) {
  const keys = Object.keys(reeks).sort();
  if (reeks[ym] != null) return reeks[ym];
  if (ym < keys[0]) return reeks[keys[0]];
  if (ym > keys[keys.length - 1]) return reeks[keys[keys.length - 1]];
  let last = reeks[keys[0]];
  for (const k of keys) { if (k > ym) break; last = reeks[k]; }
  return last;
}

// Generieke prijspeilfactor voor een reeks t.o.v. het basis-prijspeil.
function factorVoorReeks(reeks, prijspeildatum) {
  if (!prijspeildatum) return 1;
  const ym = String(prijspeildatum).slice(0, 7);
  if (!/^\d{4}-\d{2}$/.test(ym)) return 1;
  const basis = reeks[BASIS_PRIJSPEIL];
  const waarde = indexVoorReeks(reeks, ym);
  if (!basis || !waarde) return 1;
  return Math.round((waarde / basis) * 10000) / 10000;
}

// Totaal (1b) — gebruikt o.a. voor materieel en als blended scalar.
export function prijspeilFactor(prijspeildatum) { return factorVoorReeks(PRIJSINDEX, prijspeildatum); }
// 1c — component-specifiek.
export function prijspeilFactorLoon(prijspeildatum) { return factorVoorReeks(PRIJSINDEX_LOON, prijspeildatum); }
export function prijspeilFactorMateriaal(prijspeildatum) { return factorVoorReeks(PRIJSINDEX_MATERIAAL, prijspeildatum); }
